use std::fs;
use std::io::Write;

// Read in file version and create version.rs automatically
fn generate_version_rs() {
    let version = fs::read_to_string("../version").expect("Unable to read version file");

    let mut version_file =
        fs::File::create("src/version.rs").expect("Unable to create version.rs file");

    version_file
        .write_all(b"//! This file is generated by build.rs\n//! Do not edit this file manually\n")
        .expect("Unable to write to version.rs file");
    version_file
        .write_all(
            format!(
                "pub const MAJOR: &str = \"{}\";\n",
                version.lines().nth(0).unwrap()
            )
            .as_bytes(),
        )
        .expect("Unable to write to version.rs file");
    version_file
        .write_all(
            format!(
                "pub const MINOR: &str = \"{}\";\n",
                version.lines().nth(1).unwrap()
            )
            .as_bytes(),
        )
        .expect("Unable to write to version.rs file");
    version_file
        .write_all(
            format!(
                "pub const PATCH: &str = \"{}\";\n",
                version.lines().nth(2).unwrap()
            )
            .as_bytes(),
        )
        .expect("Unable to write to version.rs file");
    version_file
        .write_all(
            format!(
                "pub const SUFFIX: &str = \"{}\";\n",
                version.lines().nth(3).unwrap()
            )
            .as_bytes(),
        )
        .expect("Unable to write to version.rs file");
}

pub fn update_cargo_version(filename: &str, version_number: &str) {
    // Update Cargo.toml
    let cargo_toml = fs::read_to_string(filename).expect("Unable to read Cargo.toml file");
    // Replace whole line if it contains version
    let new_cargo_toml = cargo_toml
        .lines()
        .map(|line| {
            // Must be start of line
            if line.starts_with("version =") {
                format!("version = \"{}\"", version_number)
            } else {
                line.to_string()
            }
        })
        .collect::<Vec<String>>()
        .join("\n");

    // Write back to Cargo.toml
    fs::write(filename, new_cargo_toml).expect("Unable to write to Cargo.toml file");
}

pub fn update_cargo_files_with_version() {
    // Read major, minor, patch, suffix from version file in root
    let version = fs::read_to_string("../version").expect("Unable to read version file");

    // First line is major
    let major = version.lines().nth(0).unwrap();
    // Second line is minor
    let minor = version.lines().nth(1).unwrap();
    // Third line is patch
    let patch = version.lines().nth(2).unwrap();
    // Fourth line is suffix
    let suffix = version.lines().nth(3).unwrap();

    let version_number = format!("{}.{}.{}{}", major, minor, patch, suffix);

    // Update Cargo.toml
    update_cargo_version("../adsb/Cargo.toml", &version_number);
    update_cargo_version("../adsb_gateway/Cargo.toml", &version_number);
    update_cargo_version("../cot/Cargo.toml", &version_number);
    update_cargo_version("../example/Cargo.toml", &version_number);
    update_cargo_version("../gtfs_realtime_gateway/Cargo.toml", &version_number);
    update_cargo_version("../nmea_gateway/Cargo.toml", &version_number);
    update_cargo_version("../sensor_gateway/Cargo.toml", &version_number);
    update_cargo_version("../spx/Cargo.toml", &version_number);
    update_cargo_version("../spx_gateway/Cargo.toml", &version_number);
    update_cargo_version("../spx_server/Cargo.toml", &version_number);
    update_cargo_version("../zenoh_gateway/Cargo.toml", &version_number);
}

